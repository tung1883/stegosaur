// Builds samples.js from real `stegosaur text-embed` output so the mockups show the tool's actual cover text.
// Usage: node make-samples.js <dir containing real_<style>.txt>
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
const take = { syslog: 12, postgres: 12, nginx: 10, env: 14 };
const out = {};
for (const style of ['prose', 'syslog', 'postgres', 'nginx', 'env']) {
  const text = fs.readFileSync(path.join(dir, `real_${style}.txt`), 'utf8');
  if (style === 'prose') {
    const lines = [];
    let cur = '';
    for (const w of text.split(/\s+/).filter(Boolean)) {
      if ((cur + ' ' + w).length > 84) { lines.push(cur); cur = w; } else cur = cur ? cur + ' ' + w : w;
    }
    if (cur) lines.push(cur);
    out[style] = lines.slice(0, 8);
  } else {
    out[style] = text.split('\n').slice(0, take[style]);
  }
}
fs.writeFileSync(path.join(__dirname, 'samples.js'), '// generated by make-samples.js from real tool output\nconst REAL = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('wrote samples.js', Object.entries(out).map(([k, v]) => `${k}:${v.length}`).join(' '));
